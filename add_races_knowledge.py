def main():
    """Основная функция добавления рас в базу знаний"""
    print("🎭 Добавление знаний о расах...")
    
    km = KnowledgeManager()
    
    # Добавляем все расы
    added_count = 0
    for term, definition in ALL_RACES:
        if km.add_word_knowledge(term, definition, source="races_module"):
            added_count += 1
    
    print(f"✅ Добавлено {added_count} терминов о расах")
    
    # Генерируем обучающие пары
    print("\n📝 Генерация обучающих пар...")
    pairs_count = km.generate_training_pairs(min_difficulty="simple")
    print(f"✅ Сгенерировано {pairs_count} обучающих пар")
    
    # Объединяем с пользовательскими диалогами
    print("\n🔗 Объединение с диалогами...")
    km.merge_with_user_conversations("data/user_conversations.jsonl")
    
    # Печатаем отчёт
    km.print_report()


if __name__ == "__main__":
    main()
