def generate_world_input():
    genre = random.choice(GENRES)
    tags = ", ".join(random.sample(TAGS, k=random.randint(1, 3)))
    return f"Создай мир: {genre}, {tags}"

def generate_world_output(genre):
    name = f"{random.choice(['Темный', 'Сияющий', 'Забытый', 'Вечный', 'Падший'])} {genre}"
    description = random.choice(DESCRIPTIONS)
    law = random.choice(LAWS)
    tradition = random.choice(TRADITIONS)
    rule = random.choice(RULES)

    return f"""Название:
     - {name}
    Описание:
     - {description}
    Законы общества:
     - {law}
    Традиции:
     - {tradition}
    Внегласные правила:
     - {rule}"""

def generate_world_examples(count=50):
    examples = []
    used_inputs = set()

    while len(examples) < count:
        inp = generate_world_input()
        if inp in used_inputs:
            continue  # избегаем дублей
        used_inputs.add(inp)
        out = generate_world_output(inp)
        examples.append({"input": inp, "output": out})

    print(f"[INFO] Сгенерировано {count} примеров миров")
    return examples

if __name__ == "__main__":
    worlds = generate_world_examples(50)
    with open("generated_worlds.json", "w", encoding="utf-8") as f:
        json.dump(worlds, f, ensure_ascii=False, indent=2)
