def generate_world_input():
    genre = random.choice(GENRES)
    tag = random.choice(TAGS)
    return f"Жанр: {genre}, Тег: {tag}"

def generate_world_output(genre, tag):
    # Генерируем название
    name = f"{random.choice(NAME_PREFIXES)} {random.choice(NAME_SUFFIXES)}"
    
    # Генерируем описание
    description = random.choice(DESCRIPTION_TEMPLATES).format(genre=genre, tag=tag)
    
    return f"Название: {name}\n\nОписание: {description}"

def generate_world_examples(count=50):
    examples = []
    used_inputs = set()

    while len(examples) < count:
        genre = random.choice(GENRES)
        tag = random.choice(TAGS)
        inp = f"Жанр: {genre}, Тег: {tag}"
        
        if inp in used_inputs:
            continue  # избегаем дублей
        used_inputs.add(inp)
        
        out = generate_world_output(genre, tag)
        examples.append({"input": inp, "output": out})

    print(f"[INFO] Сгенерировано {count} примеров миров")
    return examples

if __name__ == "__main__":
    worlds = generate_world_examples(50)
    with open("generated_worlds.json", "w", encoding="utf-8") as f:
        json.dump(worlds, f, ensure_ascii=False, indent=2)
    print("[INFO] Примеры сохранены в generated_worlds.json")