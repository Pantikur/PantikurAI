from typing import List, Optional, Dict
from pydantic import BaseModel


class RaceParams(BaseModel):
    """Модель параметров расы персонажа."""
    race: Optional[str] = None  # "человек" | "эльф" | "гном" | "орк" | ...
    race_subcategory: Optional[str] = None  # подкатегория расы (например, "высший эльф", "тёмный эльф")
    
    # Физические характеристики расы
    height_range: Optional[str] = None  # "низкий" | "средний" | "высокий" | "огромный"
    build: Optional[str] = None  # "стройное" | "плотное" | "мускулистое" | "худое"
    skin_tone: Optional[str] = None  # цвет кожи, характерный для расы
    ear_shape: Optional[str] = None  # "обычные" | "заостренные" | "маленькие"
    eye_color: Optional[str] = None  # характерный цвет глаз
    hair_color: Optional[str] = None  # характерный цвет волос
    facial_hair: Optional[str] = None  # "нет" | "борода" | "усы" | "обильная растительность"
    
    # Особенности расы
    lifespan: Optional[str] = None  # "короткая" | "средняя" | "долгая" | "бессмертный"
    magic_affinity: Optional[str] = None  # "нет" | "слабая" | "средняя" | "сильная" | "врожденная"
    strength: Optional[str] = None  # "низкая" | "средняя" | "высокая" | "экстремальная"
    agility: Optional[str] = None  # "низкая" | "средняя" | "высокая" | "экстремальная"
    intelligence: Optional[str] = None  # "низкая" | "средняя" | "высокая" | "экстремальная"
    
    # Культурные особенности
    homeland: Optional[str] = None  # родная земля/место обитания
    language: Optional[str] = None  # основной язык
    profession_tendency: Optional[str] = None  # склонность к профессиям


