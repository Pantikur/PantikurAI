        self.reply_history.append(response)
        if len(self.reply_history) > 20:
            self.reply_history = self.reply_history[-20:]

        # Сохраняем сообщение
        self.conversation_count += 1

        return {
            "response": response,
            "emotion": emotion,
            "typing_time": typing_time,
            "mood": self.mood.base_mood,
            "topics": detected_topics,
            "mood_emojis": mood_emojis,
        }

