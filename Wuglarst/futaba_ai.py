    def _select_greeting(self) -> str:
        """Выбирает приветствие по времени суток."""
        hour = datetime.now().hour
        if 5 <= hour < 12:
            return random.choice(self.greetings["morning"])
        elif 12 <= hour < 18:
            return random.choice(self.greetings["day"])
        elif 18 <= hour < 23:
            return random.choice(self.greetings["evening"])
        else:
            return random.choice(self.greetings["night"])

    def _select_goodbye(self) -> str:
        """Выбирает прощание."""
        return random.choice(self.goodbyes)

    def _detect_topics(self, msg: str) -> List[str]:
        """Определяет темы разговора."""
        topics = []
        for topic, keywords in self.topic_keywords.items():
            if any(kw in msg for kw in keywords):
                topics.append(topic)
        return topics

    def _detect_emotion(self, msg: str) -> str:
        """Определяет эмоцию в сообщении."""
        msg_lower = msg.lower()
        
        happy_words = ["хорошо", "класс", "круто", "отлично", "супер", "рад", "😊", "😄", "🎉", "прекрасно"]
        sad_words = ["грустно", "плохо", "устал", "тоска", "печаль", "депрессия", "устала", "😢", "😞", "😔", "💔"]
        angry_words = ["злюсь", "бесит", "достал", "тупик", "бред", "раздражает"]
        curious_words = ["почему", "как", "зачем", "что если", "интересно", "расскажи", "объясни", "любопытно"]
        love_words = ["люблю", "❤️", "❤", "скучаю", "милая", "красивая", "любимая", "обним", "целую"]

        scores = {
            "happy": sum(1 for w in happy_words if w in msg_lower),
            "sad": sum(1 for w in sad_words if w in msg_lower),
            "angry": sum(1 for w in angry_words if w in msg_lower),
            "curious": sum(1 for w in curious_words if w in msg_lower),
            "love": sum(1 for w in love_words if w in msg_lower),
        }

        max_score = max(scores.values())
        if max_score == 0:
            return "neutral"
        
        for emotion, score in scores.items():
            if score == max_score:
                return emotion

        return "neutral"

