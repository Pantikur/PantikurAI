class ChatMood:
    """Настроение Футабы — меняется в зависимости от разговора."""

    def __init__(self):
        self.base_mood = "neutral"  # happy, calm, playful, curious, sad, annoyed, excited, sleepy, flirty, thoughtful
        self.energy = 0.7           # 0.0 — очень устала, 1.0 — на взводе
        self.friendliness = 0.8     # 0.0 — холодна, 1.0 — обнимашки
        self.sassiness = 0.3        # 0.0 — серьёзная, 1.0 — подкалывает
        self.creativity = 0.6       # 0.0 — шаблонные ответы, 1.0 — креативит
        self.conversation_depth = 0.3  # 0.0 — поверхностно, 1.0 — глубокие темы

    def update(self, user_message: str, response_sent: bool = True):
        """Обновляет настроение на основе сообщения пользователя."""
        msg_lower = user_message.lower().strip()

        # Реагируем на эмоции в сообщении пользователя
        happy_words = ["хорошо", "класс", "круто", "отлично", "супер", "рада", "люблю", "счастье", "вау", "wow", "😂", "😄", "😊", "🎉", "❤️", "😍", "🥰", "прекрасно", "замечательно", " супер"]
        sad_words = ["грустно", "плохо", "устал", "тоска", "грусть", "печаль", "депрессия", "устала", "надоело", "💔", "😢", "😞", "😔", "зачем", "бессмысленно"]
        angry_words = ["злюсь", "бесит", "достал", "тупик", "бред", "ебан", "сука", "уёб", "раздражает", "fuck", "shit"]
        curious_words = ["почему", "как", "зачем", "что если", "интересно", "расскажи", "объясни", "почему", "расскажи мне", "любопытно"]
        love_words = ["люблю", "❤️", "❤", "скучаю", "милая", "красивая", "любимая", "обним", "целую", "дорогая", "лучшая"]
        sleep_words = ["спать", "устал", "ночь", "засыпаю", "сон", "поздно", "устала", "зев", "😴", "спокойной", "good night"]

        happiness = sum(1 for w in happy_words if w in msg_lower)
        sadness = sum(1 for w in sad_words if w in msg_lower)
        anger = sum(1 for w in angry_words if w in msg_lower)
        curiosity = sum(1 for w in curious_words if w in msg_lower)
        love_score = sum(1 for w in love_words if w in msg_lower)
        sleepiness = sum(1 for w in sleep_words if w in msg_lower)

        # Корректируем настроение
        self.friendliness += 0.05 * happiness + 0.1 * love_score - 0.05 * sadness - 0.08 * anger
        self.energy += 0.03 * happiness + 0.05 * curiosity - 0.1 * sleepiness
        self.sassiness += 0.02 * happiness - 0.03 * sadness + 0.05 * (1 if anger > 0 else 0)
        self.conversation_depth += 0.02 * curiosity + 0.01 * love_score

        # Энергия выше, если пользователь активен
        if response_sent:
            self.energy = max(0.1, self.energy - 0.02)  # Немного устаём от общения

        # Ограничиваем значения
        self.friendliness = max(0.0, min(1.0, self.friendliness))
        self.energy = max(0.05, min(1.0, self.energy))
        self.sassiness = max(0.0, min(1.0, self.sassiness))
        self.conversation_depth = max(0.0, min(1.0, self.conversation_depth))

        # Определяем текущее настроение
        if self.energy > 0.8 and self.friendliness > 0.7:
            self.base_mood = "excited"
        elif sleepiness > 0:
            self.base_mood = "sleepy"
        elif sadness > happiness + 1:
            self.base_mood = "sad"
        elif anger > 0:
            self.base_mood = "annoyed"
        elif curiosity > happiness + 1:
            self.base_mood = "curious"
        elif love_score > 0:
            self.base_mood = "flirty"
        elif self.friendliness > 0.7 and self.sassiness > 0.4:
            self.base_mood = "playful"
        elif self.conversation_depth > 0.6:
            self.base_mood = "thoughtful"
        elif self.friendliness > 0.5:
            self.base_mood = "happy"
        else:
            self.base_mood = "calm"

    def get_mood_phrase(self) -> str:
        """Возвращает фразу, соответствующую настроению."""
        phrases = {
            "happy": random.choice(["~", "♪", "✨", ""]),
            "playful": random.choice(["~", "♪", "🎮", ""]),
            "excited": random.choice(["!!!", "~!", "✨✨", "🎉"]),
            "calm": "",
            "curious": "?",
            "thoughtful": "...",
            "sad": "...",
            "annoyed": ". . .",
            "flirty": "♪",
            "sleepy": "...zzz",
        }
        return phrases.get(self.base_mood, "")


