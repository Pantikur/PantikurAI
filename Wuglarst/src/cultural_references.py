def get_time_of_day():
    """Определяет время суток."""
    hour = datetime.now().hour
    if 6 <= hour < 10:
        return "morning"
    elif 10 <= hour < 18:
        return "day"
    elif 18 <= hour < 22:
        return "evening"
    else:
        return "night"

def get_cultural_phrase(style=None):
    """
    Возвращает случайную культурную фразу.
    
    :param style: Ключ категории (например, 'grandma', 'aristocrat') или None.
                  Если None — выбирается стиль по времени суток.
    :return: Строка — выбранная фраза.
    """
    # Если указан стиль — используем его
    if style and style in CATEGORIES and style != "any":
        pool = CATEGORIES[style]
        return random.choice(pool)

    # Иначе — выбираем по времени суток
    time_of_day = get_time_of_day()

    # Настройка предпочтительных стилей по времени
    style_map = {
        "night": ["cyberpunk", "neon", "fantasy_aristocrat", "fantasty", "superstition"],
        "morning": ["soviet", "village", "grandma", "religion"],
        "day": ["soviet", "aristocrat", "tsarist", "religion"],
        "evening": ["aristocrat", "fantasy_aristocrat", "neon", "religion"]
    }

    available_styles = style_map.get(time_of_day, ["any"])
    chosen_style = random.choice(available_styles)

    pool = CATEGORIES[chosen_style]
    return random.choice(pool) if pool else "Тишина. Даже бабушка не знает, что сказать…"