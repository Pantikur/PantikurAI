        npcs = world.get("npcs", [])
        alive_npcs = [n for n in npcs if n.get("alive", True)]
        if not alive_npcs:
            return "Неизвестный персонаж"
        npc = random.choice(alive_npcs)
        if npc["name"] == exclude:
            alive_npcs.remove(npc)
            if not alive_npcs:
                return "Неизвестный персонаж"
            npc = random.choice(alive_npcs)
        return npc["name"]

