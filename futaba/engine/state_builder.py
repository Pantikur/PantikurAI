    def research_topic(self, query: str) -> List[Dict[str, str]]:
        """
        Ищет информацию в интернете по запросу.
        Футаба сама формирует поисковый запрос и изучает результаты.
        """
        self.logger.info(f"🌐 Футаба ищет в интернете: '{query}'")

        results = []

        # Сначала пробуем реальный веб-поиск
        if self.web_access:
            try:
                # Используем search_legal_info для правовых запросов
                if "закон" in query or "кодекс" in query or "право" in query:
                    results = self.web_access.search_legal_info(query, "russia")
                # Используем search_management_best_practices для управленческих
                elif "управление" in query or "государство" in query:
                    results = self.web_access.search_management_best_practices(query)
                # Используем find_learning_materials для общих запросов
                else:
                    materials = self.web_access.find_learning_materials(query, max_pages=3)
                    for m in materials:
                        results.append({
                            "title": m.get("title", ""),
                            "description": "; ".join(m.get("key_points", [])),
                            "source": m.get("source", ""),
                        })
            except Exception as e:
                self.logger.warning(f"⚠️ Веб-поиск не удался: {e}")

        # Если результатов нет — используем встроенные знания Футабы
        if not results:
            self.logger.info("📖 Использую встроенные знания для построения документа")
            results = self._get_builtin_knowledge(query)

        # Логируем исследование
        self.progress["research_log"].append({
            "timestamp": datetime.now().isoformat(),
            "query": query,
            "results_count": len(results),
            "sources": [r.get("source", r.get("url", "")) for r in results[:3]],
        })

        return results

