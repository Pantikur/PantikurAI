    def _load_progress(self) -> Dict[str, Any]:
        """Загружает прогресс строительства."""
        if self.progress_file.exists():
            try:
                return json.loads(self.progress_file.read_text(encoding="utf-8"))
            except Exception:
                pass
        return {
            "started_at": datetime.now().isoformat(),
            "status": "not_started",
            "current_step": 0,
            "total_steps": len(self.STATE_DOCUMENTS),
            "completed_documents": [],
            "pending_documents": list(self.STATE_DOCUMENTS.keys()),
            "research_log": [],
            "last_updated": datetime.now().isoformat(),
        }

    def _save_progress(self):
        """Сохраняет прогресс строительства."""
        self.progress["last_updated"] = datetime.now().isoformat()
        self.progress_file.write_text(
            json.dumps(self.progress, ensure_ascii=False, indent=2),
            encoding="utf-8"
        )

    def get_progress(self) -> Dict[str, Any]:
        """Возвращает текущий прогресс строительства."""
        return self.progress

