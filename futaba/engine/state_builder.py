    def build_all(self) -> Dict[str, Any]:
        """
        Футаба создаёт все документы государства за один цикл.
        
        Returns:
            Отчёт о результатах строительства.
        """
        self.logger.info("=" * 60)
        self.logger.info("🏛️ ФУТАБА НАЧИНАЕТ СТРОИТЕЛЬСТВО ГОСУДАРСТВА ВУГЛАРСТ")
        self.logger.info("=" * 60)

        self.progress["status"] = "building"
        self.progress["started_at"] = datetime.now().isoformat()
        self._save_progress()

        results = {
            "total": len(self.STATE_DOCUMENTS),
            "created": 0,
            "failed": 0,
            "documents": [],
        }

        for filename, info in self.STATE_DOCUMENTS.items():
            self.logger.info(f"\n📝 Создание документа: {info['name']} ({filename})")
            self.logger.info(f"   Поисковый запрос: '{info['search_query']}'")

            success = self.build_document(filename)

            if success:
                results["created"] += 1
                results["documents"].append({
                    "filename": filename,
                    "name": info["name"],
                    "status": "created",
                })
                self.logger.info(f"✅ Документ создан: {info['name']}")
            else:
                results["failed"] += 1
                results["documents"].append({
                    "filename": filename,
                    "name": info["name"],
                    "status": "failed",
                })
                self.logger.error(f"❌ Ошибка создания: {info['name']}")

            # Пауза между документами
