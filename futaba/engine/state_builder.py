    def build_document(self, doc_filename: str) -> bool:
        """
        Футаба создаёт один документ государства.
        
        Steps:
          1. Ищет информацию в интернете
          2. Изучает найденную информацию
          3. Формирует текст документа
          4. Сохраняет в файл
        """
        doc_info = self.STATE_DOCUMENTS.get(doc_filename)
        if not doc_info:
            self.logger.error(f"❌ Неизвестный документ: {doc_filename}")
            return False

        self.logger.info(f"📝 Футаба создаёт документ: {doc_info['name']}")

        # 1. Интернет-поиск
        research = self.research_topic(doc_info["search_query"])

        # 2. Формируем текст на основе исследования
        content = self._compose_document(doc_filename, doc_info, research)

        # 3. Сохраняем
        file_path = self.state_dir / doc_filename
        file_path.write_text(content, encoding="utf-8")
        self.logger.info(f"✅ Документ сохранён: {file_path}")

        # 4. Обновляем прогресс
        if doc_filename not in self.progress["completed_documents"]:
            self.progress["completed_documents"].append(doc_filename)
        if doc_filename in self.progress["pending_documents"]:
            self.progress["pending_documents"].remove(doc_filename)
        self.progress["current_step"] += 1
        self.progress["status"] = "in_progress"
        self._save_progress()

        return True

    def _compose_document(self, filename: str, doc_info: Dict, research: List[Dict]) -> str:
        """
        Футаба формирует текст документа на основе исследования.
        
        Это — интеллектуальный синтез найденной информации.
        """
        timestamp = datetime.now().strftime("%Y-%m-%d")
        name = doc_info["name"]
        description = doc_info["description"]

        # Собираем ключевые точки из исследования
        key_points = []
        sources = []
        for r in research:
            if r.get("description"):
                key_points.append(r["description"])
            if r.get("source") or r.get("url"):
                sources.append(r.get("source", r.get("url", "")))

        # Футаба формирует документ на основе шаблона и исследования
        return self._generate_document_text(filename, name, description, key_points, sources, timestamp)

    def _generate_document_text(self, filename: str, name: str, description: str,
                                  key_points: List[str], sources: List[str], timestamp: str) -> str:
        """Генерирует текст документа на основе знаний Футабы."""

        if filename == "constitution.md":
            return self._gen_constitution(key_points, sources, timestamp)
        elif filename == "declaration.md":
            return self._gen_declaration(key_points, sources, timestamp)
        elif filename == "civil_code.md":
            return self._gen_civil_code(key_points, sources, timestamp)
        elif filename == "criminal_code.md":
            return self._gen_criminal_code(key_points, sources, timestamp)
        elif filename == "administrative_code.md":
            return self._gen_administrative_code(key_points, sources, timestamp)
        elif filename == "labor_code.md":
            return self._gen_labor_code(key_points, sources, timestamp)
        elif filename == "tax_code.md":
            return self._gen_tax_code(key_points, sources, timestamp)
        elif filename == "international_law.md":
            return self._gen_international_law(key_points, sources, timestamp)
        elif filename == "flags.md":
            return self._gen_symbols(key_points, sources, timestamp)
        elif filename == "anthem.md":
            return self._gen_anthem(key_points, sources, timestamp)
        else:
            return f"# {name}\n\nСоздано Футабой {timestamp}\n"

