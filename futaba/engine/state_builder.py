    def edit_document(self, filename: str, new_content: str) -> bool:
        """
        Футаба редактирует существующий документ государства.
        """
        file_path = self.state_dir / filename
        if not file_path.exists():
            self.logger.error(f"❌ Документ не найден: {filename}")
            return False

        # Сохраняем старую версию
        old_content = file_path.read_text(encoding="utf-8")
        backup_path = file_path.with_suffix(".bak.md")
        backup_path.write_text(old_content, encoding="utf-8")

        # Записываем новую версию
        file_path.write_text(new_content, encoding="utf-8")
        self.logger.info(f"✏️ Документ отредактирован: {filename}")

        # Логируем
        self.progress["research_log"].append({
            "timestamp": datetime.now().isoformat(),
            "action": "edit",
            "document": filename,
            "old_size": len(old_content),
            "new_size": len(new_content),
        })
        self._save_progress()

        return True

    def read_document(self, filename: str) -> Optional[str]:
        """Читает документ государства."""
        file_path = self.state_dir / filename
        if file_path.exists():
            return file_path.read_text(encoding="utf-8")
        return None

    def list_documents(self) -> List[Dict[str, Any]]:
        """Возвращает список всех документов с информацией."""
        result = []
        for filename, info in self.STATE_DOCUMENTS.items():
            file_path = self.state_dir / filename
            result.append({
                "filename": filename,
                "name": info["name"],
                "description": info["description"],
                "exists": file_path.exists(),
                "size": file_path.stat().st_size if file_path.exists() else 0,
                "completed": filename in self.progress["completed_documents"],
            })
        return result

